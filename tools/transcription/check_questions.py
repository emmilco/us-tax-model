"""Standing question review (question_review.py), offline, in check-all. Sampled reviews (samples.py).

Every question (an input line of the jurisdiction's forms) has a record in its form's log,
reviews/<year>/questions/<form>.json, holding the samples run against one subject (question_review.subject: the
question's line, its interview wording and help, and each direct reader's line and English).

- A question whose subject differs from its record's (or that has none, or is logged under another form) is `due`:
  counted on the console and listed in the report, not failed. It is reviewed with
  `python3 tools/transcription/question_review.py --inputs <input>`.
- Each current sample whose verdict is not MATCH is `unruled:<input>#<k>` until its findings are adjudicated and
  ruled in reviews/<year>/questions/rulings.json with the record's `subject_sha`; a ruling with another subject_sha is
  not accepted. A sample whose verdict and normalised findings equal those of a ruled sample of the same question
  carries that ruling. Unruled samples fail check-all, unless held by the baseline (tools/baseline_check.py; written
  with --baseline), each entry held while its subject is unchanged.
- A logged review whose input is no longer a question is an `orphan` (fails).

`--release` also fails on every due question and every question short of the milestone's samples, and writes no
report. It is the release gate once the first full pass is ruled; tools/release_reviews.sh does not call it yet.

    check_questions.py [--release] [--baseline] [--jurisdiction ny]
"""
import json
import os
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent))
import question_review as Q  # noqa: E402
import samples  # noqa: E402
from transcribe import ROOT  # noqa: E402
from taxyear import Y  # noqa: E402
import baseline_check  # noqa: E402
import jurisdiction  # noqa: E402

RULINGS = Path(Q.OUT) / "rulings.json"
REPORT = jurisdiction.ypath("reports", Y, "question_currency.md")


def findings(ctx, reviewed):
    """(found, shas): every question's findings, release kinds included, orphans, and each question's current
    subject. `ctx` is a question_review.Ctx; `reviewed` question_review.records()."""
    out, shas = [], {}
    current = ctx.units()
    for inp in current:
        sha = shas[inp] = ctx.subject(inp)
        form = ctx.lines[inp][0]
        held = reviewed.get(inp)
        r = held[1] if held and held[0] == form else None
        why = ("logged under another form" if held and not r
               else "the question, its wording or help, or its readers changed since its samples")
        out += samples.unit_findings(inp, form, sha, r, why, "MATCH", f"question_review.py --inputs {inp}")
    for inp in sorted(set(reviewed) - set(current)):
        out.append({"kind": "orphan", "line": inp, "form": reviewed[inp][0] or "-", "subject": inp,
                    "detail": f"a logged review whose input is no longer a question; remove it from {reviewed[inp][0]}.json"})
    return out, shas


def check(release=False, rebaseline=False):
    forms = baseline_check.load_forms(Path(ROOT) / "canonical" / Y)
    found, shas = findings(Q.Ctx.load(), Q.records())
    due = [f for f in found if f["kind"] == "due"]
    if not release:
        found = [f for f in found if f["kind"] not in ("due", "short")]
        if due:
            print(f"  {len(due)} question(s) due at the next full pass; listed in {os.path.relpath(REPORT, ROOT)}")
    data = json.loads(RULINGS.read_text()) if RULINGS.exists() else {}
    good = samples.accepted(data.get("rulings", {}), shas)
    carry = samples.carried(found, good)
    if carry:
        print(f"  {len(carry)} sample(s) carry the ruling of an equal sample on the same question")
    with tempfile.TemporaryDirectory() as tmp:  # run() sees only the accepted and carried rulings
        view = Path(tmp) / RULINGS.name
        view.write_text(json.dumps({**data, "rulings": {**good, **carry}}))
        status = baseline_check.run(
            "questions", forms, found, view, Path(tmp) / "report.md" if release else REPORT, "Standing question review",
            "Generated by `tools/transcription/check_questions.py`. `unruled`: a current sample (`<input>#<sample>`) "
            "found NARROW, WIDE, WRONG_FIGURE, TYPE or UNCLEAR cases not yet ruled; a ruling with `carried_from` is "
            "carried from an equal sample. `orphan`: a logged review whose input is no longer a question. `due` and "
            "`short` appear only in release mode.", rebaseline)
        if rebaseline:
            data["baseline"] = json.loads(view.read_text())["baseline"]
            RULINGS.parent.mkdir(parents=True, exist_ok=True)
            RULINGS.write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8")
    if due and not release:
        with open(REPORT, "a", encoding="utf-8") as out:
            out.write(f"\n## Due at the next full pass ({len(due)})\n\n"
                      + "".join(f"- `{f['line']}` ({f['form']}): {f['detail']}\n" for f in due))
    return status


def self_test():
    """findings() on the synthetic forms of question_review's self-test."""
    eng = lambda d, i: f"English of {i}"
    ctx = Q.Ctx(Q._test_lines(), english=eng)
    sha = ctx.subject("f.amt")
    rec = lambda verdict, subject=sha: {"subject_sha": subject, "samples": [{"verdict": verdict, "findings": [{"kind": verdict}]}]}
    kinds = lambda reviewed: {f["line"]: f["kind"] for f in findings(ctx, reviewed)[0]}
    saved = samples.SAMPLES_PER_MILESTONE
    try:
        samples.SAMPLES_PER_MILESTONE = 1
        assert kinds({}) == {i: "due" for i in ctx.units()}
        match_all = {i: ("f", rec("MATCH", ctx.subject(i))) for i in ctx.units()}
        assert kinds(match_all) == {}
        assert kinds(dict(match_all, **{"f.amt": ("f", rec("NARROW"))})) == {"f.amt#1": "unruled"}
        assert kinds(dict(match_all, **{"f.amt": ("f", rec("NARROW", "old"))})) == {"f.amt": "due"}
        assert kinds(dict(match_all, **{"f.amt": ("g", rec("MATCH"))})) == {"f.amt": "due"}, "logged under another form"
        assert kinds(dict(match_all, **{"f.gone": ("f", rec("MATCH"))})) == {"f.gone": "orphan"}
        found, shas = findings(ctx, dict(match_all, **{"f.amt": ("f", rec("NARROW"))}))
        good = {"unruled:f.amt#1": {"subject_sha": sha, "class": "model error"}}
        assert samples.accepted({"unruled:f.amt#1": {"subject_sha": "older"}}, shas) == {}
        assert samples.accepted(good, shas) == good
        twice = {"subject_sha": sha, "samples": rec("NARROW")["samples"] * 2}
        found2, _ = findings(ctx, dict(match_all, **{"f.amt": ("f", twice)}))
        assert set(samples.carried(found2, good)) == {"unruled:f.amt#2"}
        samples.SAMPLES_PER_MILESTONE = 2
        assert set(kinds(match_all).values()) == {"short"}
    finally:
        samples.SAMPLES_PER_MILESTONE = saved
    print("check_questions self-test: ok")
    return 0


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        sys.exit(self_test())
    os.chdir(ROOT)
    import build_fresh
    build_fresh.require()
    sys.exit(check(release="--release" in sys.argv, rebaseline="--baseline" in sys.argv))
