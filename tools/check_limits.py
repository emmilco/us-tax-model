"""Limit-sentence worklist (T-089), offline, in check-all.

Limits that apply across entries or years ("can't be more than", "limited to", "per calendar year", "for all of the
businesses") are easy to encode per entry or to leave out (BUG-0063, BUG-0069, BUG-0148, BUG-0201). Every sentence
with such a phrase on a page any form cites must be ruled in reviews/<year>/limits.json:

    "limit:<doc>:p<page>:<hash>": {"enforced_by": ["<line or gate id>", ...], "reason": "..."}
                               or {"not_applicable": "<why: another form's rule, refused by <gate>, ...>"}

An `enforced_by` id must exist. Sentences on cited pages when the check was introduced form the baseline
(tools/baseline_check.py), each held while the sentence is unchanged.

    check_limits.py [--baseline] | --self-test
"""
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from taxyear import Y  # noqa: E402
from citations import citations, form_files, segments  # noqa: E402
import baseline_check  # noqa: E402
import archive_text  # noqa: E402

CANONICAL = ROOT / "canonical" / Y
SOURCES = ROOT / "sources" / Y
RULINGS = ROOT / "reviews" / Y / "limits.json"
REPORT = ROOT / "reports" / Y / "limits.md"
PHRASE = re.compile(
    r"(can.t be more than|cannot be more than|can.t exceed|cannot exceed|is limited to|are limited to|"
    r"limited to (?:a maximum|one|the)|no more than|not more than|per calendar year|for all of (?:the|your)|"
    r"total of the amounts .{0,80}can.t|across all|each (?:person|individual|taxpayer|year)'s)", re.I)


def cited_pages():
    cited = {}
    for path in form_files():
        for doc, locator, _ in citations(path):
            for seg_doc, pages, _, _, _ in segments(doc, locator):
                cited.setdefault(seg_doc, set()).update(pages)
    return cited


def sentences(text):
    return [s.strip() for s in re.split(r"(?<=[.!?])\s+", re.sub(r"\s+", " ", text)) if s.strip()]


def findings():
    out = []
    archive = archive_text.manifest(SOURCES)
    for doc, pages in sorted(cited_pages().items()):
        if "cols_file" not in archive.get(doc, {}):
            continue
        text = archive_text.read(SOURCES, archive[doc], key="cols_file").split("\f")
        for page in sorted(pages):
            if not 0 < page <= len(text):
                continue
            for s in sentences(text[page - 1]):
                if PHRASE.search(s):
                    h = hashlib.sha256(s.encode()).hexdigest()[:8]
                    out.append({"kind": "limit", "line": f"{doc}:p{page}:{h}", "form": doc, "subject": s,
                                "detail": f"{doc} p. {page}: \"{s[:200]}\""})
    seen, unique = set(), []
    for f in out:
        if f["line"] not in seen:
            seen.add(f["line"])
            unique.append(f)
    return unique


def check_rulings():
    data = json.loads(RULINGS.read_text()) if RULINGS.exists() else {}
    ids = {l["id"] for f in baseline_check.load_forms(CANONICAL) for l in f["lines"]}
    errors = []
    for k, r in data.get("rulings", {}).items():
        if not isinstance(r, dict) or not (r.get("enforced_by") or r.get("not_applicable")):
            errors.append(f"  ruling {k}: give enforced_by (line or gate ids) or not_applicable (a reason)")
        for i in r.get("enforced_by", []) if isinstance(r, dict) else []:
            if i not in ids:
                errors.append(f"  ruling {k}: enforced_by names {i}, which is not a line")
    return errors


def check(rebaseline=False):
    forms = baseline_check.load_forms(CANONICAL)
    status = baseline_check.run(
        "limits", forms, findings(), RULINGS, REPORT, "Limit-sentence worklist",
        "Generated by `tools/check_limits.py` (T-089): limit and aggregation sentences on cited pages, each ruled to "
        "the line or gate that enforces it, or not applicable with a reason.", rebaseline)
    errors = check_rulings()
    for e in errors:
        print(e)
    return 1 if status or errors else 0


def self_test():
    assert PHRASE.search("You are limited to taking one emergency personal expense distribution per calendar year")
    assert PHRASE.search("the total of the amounts on line 2 of all Form(s) 7206 can't be more than")
    assert not PHRASE.search("Enter the amount from line 3.")
    assert sentences("One. Two two.  Three?") == ["One.", "Two two.", "Three?"]
    print("limits self-test: ok")
    return 0


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        sys.exit(self_test())
    sys.exit(check(rebaseline="--baseline" in sys.argv))
