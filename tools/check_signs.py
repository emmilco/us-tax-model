"""Sign rule (T-086), offline, in check-all.

A rate product (`multiply_rate`, `prorate`) whose amount operand is a signed `Dollars` line takes the sign of that
amount: a negative amount gives a negative product, which a printed instruction written for positive amounts does not
foresee ("Multiply line 2 by 7.5%" on a negative AGI). Such a line needs a floor on the amount (a NonNegDollars
operand) or a ruling that the amount cannot be negative on a reachable return, giving the reason.

Rulings and baseline: reviews/<year>/signs.json (tools/baseline_check.py); report: reports/<year>/signs.md.

    check_signs.py [--baseline] | --self-test
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from taxyear import Y  # noqa: E402
import baseline_check  # noqa: E402
from baseline_check import line_subject  # noqa: E402

CANONICAL = ROOT / "canonical" / Y
RULINGS = ROOT / "reviews" / Y / "signs.json"
REPORT = ROOT / "reports" / Y / "signs.md"
RATE_OPS = {"multiply_rate": "amount", "prorate": "amount"}


def amount_of(expr):
    """The amount operand of a rate product, found anywhere in an expression (choose alternatives included)."""
    if isinstance(expr, dict):
        op = expr.get("op")
        if op in RATE_OPS and isinstance(expr.get(RATE_OPS[op]), str):
            yield op, expr[RATE_OPS[op]]
        for k, v in expr.items():
            if k != "op":
                yield from amount_of(v)
    elif isinstance(expr, list):
        for v in expr:
            yield from amount_of(v)


def findings(forms):
    types = {l["id"]: l.get("type") for f in forms for l in f["lines"]}
    out = []
    for form in forms:
        for line in form["lines"]:
            for op, amount in amount_of(line.get("expr")):
                if types.get(amount) == "Dollars":
                    out.append({"kind": "sign", "line": line["id"], "subject": line_subject(line), "form": form["id"],
                                "detail": f"`{op}` of `{amount}`, a signed Dollars line"})
    return out


def check(rebaseline=False):
    forms = baseline_check.load_forms(CANONICAL)
    return baseline_check.run(
        "signs", forms, findings(forms), RULINGS, REPORT, "Sign rule",
        "Generated by `tools/check_signs.py` (T-086): rate products of a signed `Dollars` amount, which need a floor or "
        "a ruling that the amount cannot be negative on a reachable return.", rebaseline)


def self_test():
    forms = [{"id": "x", "lines": [
        {"id": "x.a", "type": "Dollars", "expr": {"op": "input"}},
        {"id": "x.b", "type": "NonNegDollars", "expr": {"op": "input"}},
        {"id": "x.p", "type": "Dollars", "expr": {"op": "multiply_rate", "amount": "x.a", "rate": {"param": "r"}}},
        {"id": "x.q", "type": "Dollars", "expr": {"op": "multiply_rate", "amount": "x.b", "rate": {"param": "r"}}}]}]
    assert [f["line"] for f in findings(forms)] == ["x.p"]
    print("signs self-test: ok")
    return 0


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        sys.exit(self_test())
    sys.exit(check(rebaseline="--baseline" in sys.argv))
