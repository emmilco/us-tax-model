"""The volatile figures of the entry documents, generated between markers from the files that hold them.

    doc_figures.py              write every block
    doc_figures.py --check      fail, naming each block, when a block is not what the tool would write
    doc_figures.py --self-test

A block is the text between `<!-- figures:NAME -->` and `<!-- /figures:NAME -->` in one of the files below; the
prose around it is written by hand. The blocks: the State figures of HANDOFF-NEXT-SESSION.md, and the headline
figures of README.md and docs/TRUST.md (the ambiguity register, the citation check, the opaque count, the
scoreboard, the bug inventory). Each figure is read from the tree:

- the bug inventory: its entries and highest id (BUG_INVENTORY.md); the open entries, from the first lines of
  reports/bug_status.md when that report exists (tools/bug_status.py writes it), else not counted;
- the task register: its rows whose status is not done or closed (TASKS.md);
- the scoreboard and its sub-counts (reports/<year>/evidence.md), the estimated filer coverage
  (reports/<year>/filer_coverage.md), the citation anchors and quotes (reports/<year>/citations.md), the lines
  using `opaque` (reports/<year>/coverage.md);
- the ambiguity register's entries (ambiguities/<year>.yaml) and those an `ambiguity:` field of a line in
  forms/<year>/ links, as engine/src/check.ts counts them.

The one figure not read from the tree is the last release: the newest tag r<YYYY>.<MM>.<DD>.<n> reachable from
HEAD. A file cannot name the commit that holds it, so the block names the release and points to
`git describe` for the commits after it. --check also accepts the release before the newest when the newest
tag is on HEAD and the tracked files equal HEAD's: that is the release commit itself, tagged after its run.
The first commit after a release must therefore refresh the block.

check-all runs --check in the docs tier, after the steps that rewrite the reports it reads.
"""
import re
import subprocess
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from taxyear import Y  # noqa: E402

HANDOFF = Path("HANDOFF-NEXT-SESSION.md")
README = Path("README.md")
TRUST = Path("docs") / "TRUST.md"
INVENTORY = Path("BUG_INVENTORY.md")
TASKS = Path("TASKS.md")
BUG_REPORT = Path("reports") / "bug_status.md"
EVIDENCE = Path("reports") / Y / "evidence.md"
FILER = Path("reports") / Y / "filer_coverage.md"
CITATIONS = Path("reports") / Y / "citations.md"
COVERAGE = Path("reports") / Y / "coverage.md"
REGISTER = Path("ambiguities") / f"{Y}.yaml"
FORMS = Path("forms") / Y
GENERATED = "<!-- Generated by tools/doc_figures.py (check-all runs it with --check); do not edit between these markers. -->"
WIDTH = 118
TAG = re.compile(r"^r(\d{4})\.(\d{2})\.(\d{2})\.(\d+)$")


def start(name):
    return f"<!-- figures:{name} -->"


def end(name):
    return f"<!-- /figures:{name} -->"


def need(pattern, text, what):
    m = re.search(pattern, text, re.M)
    if not m:
        raise SystemExit(f"doc_figures: {what}: no line matches {pattern!r}; the report's format changed")
    return m


def n(x):
    return f"{int(x):,}"


# --- the figures --------------------------------------------------------------------------------------------

def bugs(text):
    ids = [int(i) for i in re.findall(r"^## BUG-(\d{4}) ", text, re.M)]
    if not ids:
        raise SystemExit(f"doc_figures: {INVENTORY}: no entries")
    return {"bugs": len(ids), "bug_max": max(ids)}


def bug_open(text):
    """The open entries and how many a task row covers, from the report's first lines; None without the report."""
    if text is None:
        return None
    m = need(r"^Open: (\d+), of which (\d+) are covered by a row of `TASKS\.md` and (\d+) by none\.$", text, BUG_REPORT)
    return {"open": int(m.group(1)), "covered": int(m.group(2))}


def tasks_open(text):
    rows = re.findall(r"^\| T-\d{3} \|.*\| ([^|]*?) \|\s*$", text, re.M)
    if not rows:
        raise SystemExit(f"doc_figures: {TASKS}: no task rows")
    return sum(1 for status in rows if not re.match(r"(done|closed)\b", status.strip()))


def scoreboard(text):
    m = need(r"Share of computed lines with at least one outside-family assertion: (\d+) of (\d+) \(([\d.]+)%\)\. "
             r"H \(human source reading\): (\d+), B \(human worked values\): (\d+), second-family M: (\d+), E: (\d+)\.",
             text, EVIDENCE)
    keys = ("lines", "computed", "pct", "h", "b", "m", "e")
    return {k: (v if k == "pct" else int(v)) for k, v in zip(keys, m.groups())}


def filer(text):
    return need(r"^\*\*Estimated coverage: ([\d.]+)%\*\*", text, FILER).group(1)


def citations(text):
    return {k: int(need(rf"^- {k}: (\d+)$", text, CITATIONS).group(1)) for k in ("anchors", "quotes")}


def opaque(text):
    m = need(r"^(\d+) of (\d+) lines use `opaque`", text, COVERAGE)
    return {"opaque": int(m.group(1)), "lines": int(m.group(2))}


def ambiguities(register_text, form_texts):
    """(entries in the register, entries some line links by an `ambiguity:` field)."""
    ids = set(re.findall(r"^\s*- id: (\S+)\s*$", register_text, re.M))
    if not ids:
        raise SystemExit(f"doc_figures: {REGISTER}: no entries")
    linked = set()
    for text in form_texts:
        linked |= {v.strip("'\"") for v in re.findall(r"^\s*ambiguity:\s*(\S+)\s*$", text, re.M)}
    return len(ids), len(ids & linked)


def release_tags(names):
    """The release tags among `names`, newest first."""
    tags = [(tuple(int(g) for g in TAG.match(t).groups()), t) for t in names if TAG.match(t)]
    return [t for _, t in sorted(tags, reverse=True)]


def tag_date(tag):
    y, mo, d, _ = TAG.match(tag).groups()
    return f"{y}-{mo}-{d}"


# --- the blocks ---------------------------------------------------------------------------------------------

def release_line(tag):
    if tag is None:
        return "- **Last release:** no release tag (`r<YYYY>.<MM>.<DD>.<n>`) is reachable from this commit."
    return (f"- **Last release:** `{tag}` ({tag_date(tag)}), the newest release tag before this commit; "
            "`git describe --tags --match 'r*'` gives the commits after it (a file cannot name the commit that holds it).")


def blocks(f, tag):
    """{(file, name): text between the markers} for the figures `f` and the release `tag`."""
    s = f["score"]
    amb, linked = f["amb"]
    if f["bug_open"] is None:
        open_bugs = "open entries not counted here (no `reports/bug_status.md`)"
    else:
        open_bugs = (f"{f['bug_open']['open']} open, {f['bug_open']['covered']} of them covered by a `TASKS.md` row "
                     "(`reports/bug_status.md`)")
    unlinked = "; each of the others says why it stands unlinked" if linked < amb else ""
    score = f"**{n(s['lines'])} of {n(s['computed'])} ({s['pct']}%)**"
    bullets = [
        release_line(tag),
        f"- **Figures**, read from this tree: `BUG_INVENTORY.md` {n(f['bugs'])} entries (highest BUG-{f['bug_max']:04d}), "
        f"{open_bugs}; `TASKS.md` {n(f['tasks'])} rows not done; scoreboard {n(s['lines'])} of {n(s['computed'])} "
        f"computed lines ({s['pct']}%, `{EVIDENCE.as_posix()}`); estimated filer coverage {f['filer']}% of returns "
        f"(`{FILER.as_posix()}`); {n(amb)} ambiguity entries, {n(linked)} linked to a line (`{REGISTER.as_posix()}`).",
    ]
    wrapped = [textwrap.fill(b, WIDTH, subsequent_indent="  ", break_long_words=False, break_on_hyphens=False)
               for b in bullets]
    state = "\n".join(["", GENERATED, "", *wrapped, ""])
    cites = f"{n(f['cite']['anchors'])} anchors and {n(f['cite']['quotes'])} quotes"
    return {
        (HANDOFF, "handoff-state"): state,
        (README, "readme-ambiguities"): f"{n(amb)} so far",
        (README, "readme-ambiguities-linked"): f"{n(linked)} of the {n(amb)} entries are linked that way{unlinked}",
        (README, "readme-citations"): cites,
        (README, "readme-opaque"): f"{n(f['opaque']['opaque'])} of {n(f['opaque']['lines'])} lines use it",
        (README, "readme-scoreboard"):
            f"In the report committed with this page it reads {score}: {n(s['m'])} lines backed by second-family "
            f"hand-work (counting lines credited through exact copies of a worked line) and {n(s['e'])} by an outside "
            "engine, with overlap.",
        (README, "readme-bugs"): f"{n(f['bugs'])} so far",
        (TRUST, "trust-citations"): cites,
        (TRUST, "trust-opaque"): f"{n(f['opaque']['opaque'])} of {n(f['opaque']['lines'])} lines",
        (TRUST, "trust-scoreboard"):
            f"{score}, with H {n(s['h'])}, B {n(s['b'])}, second-family M {n(s['m'])} and E {n(s['e'])}",
        (TRUST, "trust-ambiguities"):
            f"{n(linked)} of the {n(amb)} entries for {Y} are linked that way{unlinked}",
    }


def splice(text, name, body, where):
    """`text` with the block `name` replaced by `body`; exits when the markers are missing or repeated."""
    s, e = start(name), end(name)
    if text.count(s) != 1 or text.count(e) != 1 or text.find(s) > text.find(e):
        raise SystemExit(f"doc_figures: {where}: needs exactly one {s} followed by one {e}")
    i, j = text.find(s) + len(s), text.find(e)
    return text[:i] + body + text[j:]


def current(text, name):
    s, e = start(name), end(name)
    i, j = text.find(s), text.find(e)
    return None if i < 0 or j < i else text[i + len(s):j]


def stale_blocks(texts, want):
    """[(file, name)] whose text in `texts` ({file: text}) differs from `want`, in `want`'s order."""
    return [(path, name) for (path, name), body in want.items() if current(texts[path], name) != body]


# --- reading the tree ---------------------------------------------------------------------------------------

def read(rel):
    return (ROOT / rel).read_text(encoding="utf-8")


def figures():
    report = ROOT / BUG_REPORT
    return {
        **bugs(read(INVENTORY)),
        "bug_open": bug_open(report.read_text(encoding="utf-8") if report.exists() else None),
        "tasks": tasks_open(read(TASKS)),
        "score": scoreboard(read(EVIDENCE)),
        "filer": filer(read(FILER)),
        "cite": citations(read(CITATIONS)),
        "opaque": opaque(read(COVERAGE)),
        "amb": ambiguities(read(REGISTER), [p.read_text(encoding="utf-8") for p in sorted((ROOT / FORMS).glob("*.yaml"))]),
    }


def git(*args):
    r = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else None


def releases():
    """(the release tags reachable from HEAD, newest first; whether the newest is on HEAD with the tracked files
    unchanged from HEAD's)."""
    tags = release_tags((git("tag", "--merged", "HEAD", "--list", "r*") or "").splitlines())
    on_head = bool(tags) and git("rev-parse", f"{tags[0]}^{{commit}}") == git("rev-parse", "HEAD")
    clean = subprocess.run(["git", "diff", "--quiet", "HEAD", "--"], cwd=ROOT).returncode == 0
    return tags, on_head and clean


def accepted_tags(tags, release_commit):
    """The release tags a block may name: the newest, and on the release commit itself the one before it."""
    newest = tags[0] if tags else None
    if release_commit:
        return [newest, tags[1] if len(tags) > 1 else None]
    return [newest]


def main(argv):
    if "--self-test" in argv:
        return self_test()
    f = figures()
    tags, release_commit = releases()
    candidates = [blocks(f, t) for t in accepted_tags(tags, release_commit)]
    paths = [HANDOFF, README, TRUST]
    texts = {p: read(p) for p in paths}
    for (path, name) in candidates[0]:
        splice(texts[path], name, "", path)  # the markers are present, once each
    if "--check" in argv:
        stale = min((stale_blocks(texts, want) for want in candidates), key=len)
        if stale:
            print("doc_figures: out of date: " + ", ".join(f"{p.as_posix()} ({name})" for p, name in stale)
                  + "; run python3 tools/doc_figures.py", file=sys.stderr)
            return 1
        print(f"doc_figures: {len(candidates[0])} blocks current in {', '.join(p.as_posix() for p in paths)}")
        return 0
    out = dict(texts)
    for (path, name), body in candidates[0].items():
        out[path] = splice(out[path], name, body, path)
    changed = [p for p in paths if out[p] != texts[p]]
    for p in changed:
        (ROOT / p).write_text(out[p], encoding="utf-8")
    print(f"doc_figures: wrote {len(candidates[0])} blocks; changed: {', '.join(p.as_posix() for p in changed) or 'none'}")
    return 0


# --- self-test ----------------------------------------------------------------------------------------------

def self_test():
    """Plant a stale block, a missing marker and a release tagged after its commit; check the parsers on samples."""
    sample = {
        "bugs": 12, "bug_max": 12, "bug_open": None, "tasks": 3, "filer": "78.4",
        "score": {"lines": 559, "computed": 2915, "pct": "19.2", "h": 0, "b": 0, "m": 446, "e": 223},
        "cite": {"anchors": 5772, "quotes": 6386}, "opaque": {"opaque": 0, "lines": 4504}, "amb": (93, 92),
    }
    want = blocks(sample, "r2026.11.09.1")
    texts = {p: "" for p in (HANDOFF, README, TRUST)}
    for (path, name), body in want.items():
        texts[path] += f"prose {start(name)}{body}{end(name)} prose\n"
    assert stale_blocks(texts, want) == [], stale_blocks(texts, want)
    planted = dict(texts)
    planted[README] = planted[README].replace("12 so far", "11 so far")
    assert stale_blocks(planted, want) == [(README, "readme-bugs")], stale_blocks(planted, want)
    newer = blocks({**sample, "score": {**sample["score"], "lines": 560}}, "r2026.11.09.1")
    assert [k[1] for k in stale_blocks(texts, newer)] == ["handoff-state", "readme-scoreboard", "trust-scoreboard"]
    assert "**559 of 2,915 (19.2%)**" in want[(TRUST, "trust-scoreboard")]
    assert "each of the others says why" in want[(README, "readme-ambiguities-linked")]
    assert "says why" not in blocks({**sample, "amb": (5, 5)}, None)[(TRUST, "trust-ambiguities")]
    assert "no release tag" in blocks(sample, None)[(HANDOFF, "handoff-state")]
    assert "(2026-11-09)" in want[(HANDOFF, "handoff-state")]
    assert "open entries not counted" in want[(HANDOFF, "handoff-state")]
    counted = blocks({**sample, "bug_open": {"open": 70, "covered": 50}}, None)[(HANDOFF, "handoff-state")]
    assert "70 open, 50 of them covered" in counted, counted
    # The splice replaces only between the markers, and refuses missing or repeated markers.
    assert splice(f"a {start('x')}old{end('x')} b", "x", "new", "t") == f"a {start('x')}new{end('x')} b"
    for bad in ("no markers", f"{start('x')}{end('x')}{start('x')}{end('x')}", f"{end('x')}{start('x')}"):
        try:
            splice(bad, "x", "new", "t")
            raise AssertionError(f"splice accepted {bad!r}")
        except SystemExit:
            pass
    # Releases: newest first by date and number, not by name order; the release commit may name the one before.
    tags = release_tags(["r2026.11.09.1", "draft-v2", "r2026.11.10.1", "r2026.11.09.2", "rx"])
    assert tags == ["r2026.11.10.1", "r2026.11.09.2", "r2026.11.09.1"], tags
    assert accepted_tags(tags, False) == ["r2026.11.10.1"]
    assert accepted_tags(tags, True) == ["r2026.11.10.1", "r2026.11.09.2"]
    assert accepted_tags([], False) == [None]
    # The parsers, on lines in the reports' formats.
    assert bugs("## BUG-0001 — a\n\n## BUG-0002 — b\n") == {"bugs": 2, "bug_max": 2}
    assert bug_open("Open: 70, of which 50 are covered by a row of `TASKS.md` and 20 by none.\n") == {"open": 70, "covered": 50}
    table = "| Id | Task | Source | Due when | Status |\n| --- |\n| T-001 | a | s | d | open |\n" \
            "| T-002 | b | s | d | done 2026-11-01 (abc) |\n| T-003 | c | s | d | in progress |\n"
    assert tasks_open(table) == 2
    ev = ("**Scoreboard.** Share of computed lines with at least one outside-family assertion: 559 of 2915 (19.2%). "
          "H (human source reading): 0, B (human worked values): 0, second-family M: 446, E: 223.")
    assert scoreboard(ev) == sample["score"], scoreboard(ev)
    assert filer("**Estimated coverage: 78.4%** of returns.") == "78.4"
    assert citations("- anchors: 5772\n- anchors ruled: 53\n- quotes: 6386\n") == sample["cite"]
    assert opaque("0 of 4504 lines use `opaque` (share 0.0000)") == sample["opaque"]
    reg = "register:\n  entries:\n    - id: amb.a\n      x: 1\n    - id: amb.b\n    - id: amb.c\n"
    assert ambiguities(reg, ["  - id: l1\n    ambiguity: amb.a\n", "    ambiguity: 'amb.b'\n    ambiguity: amb.z\n"]) == (3, 2)
    try:
        scoreboard("Scoreboard: changed wording")
        raise AssertionError("scoreboard accepted a changed format")
    except SystemExit:
        pass
    print("doc_figures self-test: ok")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
