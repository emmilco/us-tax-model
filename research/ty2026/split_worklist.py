#!/usr/bin/env python3
"""Split the 2025-to-2026 year-diff worklist (reports/2026/year_diff_from_2025.md) into
(a) items with changed text or amounts in a document that has a 2026 source, and
(b) items waiting only because a cited document has no 2026 source yet,
ordered with the TY2026 priority forms first. Writes reports/2026/worklist_split.md and
research/ty2026/worklist.json. Reads only the report, the 2025 definitions and the catalogs."""
import collections, json, re, sys
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[2]
REPORT = ROOT / "reports/2026/year_diff_from_2025.md"
PRIORITY = ["f1040", "qdcg", "tcw", "tax_on_amount", "s1", "sa", "sb", "interest", "div", "sd", "sdtw",
            "clcw", "clcw26", "sales", "f8889", "w2"]
PRIORITY_NAMES = {"f1040": "Form 1040", "qdcg": "Form 1040 (Qualified Dividends and Capital Gain Tax Worksheet)",
                  "tcw": "Form 1040 (Tax Computation Worksheet)", "tax_on_amount": "Form 1040 (tax on an amount)",
                  "s1": "Schedule 1", "sa": "Schedule A", "sb": "Schedule B", "interest": "Schedule B (interest entries)",
                  "div": "Schedule B (dividend entries)", "sd": "Schedule D", "sdtw": "Schedule D Tax Worksheet",
                  "clcw": "Schedule D (Capital Loss Carryover Worksheet)", "clcw26": "Schedule D (carryover to 2026)",
                  "sales": "Form 8949", "f8889": "Form 8949" if False else "Form 8889", "w2": "Form W-2 inputs"}
NO_EDITION = "no edition in one year"


def param_readers():
    """parameter id -> the 2025 forms whose lines read it."""
    readers = collections.defaultdict(set)
    for path in sorted((ROOT / "forms/2025").glob("*.yaml")):
        text = path.read_text()
        for m in re.finditer(r"(?:ref|param): ([A-Za-z0-9_.]+)", text):
            readers[m.group(1)].add(path.stem)
    return readers


def id_files():
    """line or collection id -> the 2025 form file that defines it."""
    out = {}
    for path in sorted((ROOT / "forms/2025").glob("*.yaml")):
        for m in re.finditer(r"^\s*-?\s*id: ['\"]?([^'\"\s]+)", path.read_text(), re.M):
            out.setdefault(m.group(1), path.stem)
    return out


def parse():
    lines = REPORT.read_text().splitlines()
    start = lines.index("## Worklist")
    end = lines.index("## Below the worklist")
    items, cur = [], None
    for ln in lines[start + 1:end]:
        m = re.match(r"^### (\w+) `([^`]+)` \(([^)]+)\)$", ln)
        if m:
            cur = {"kind": m.group(1), "id": m.group(2), "file": m.group(3), "findings": []}
            items.append(cur)
            continue
        m = re.match(r"^- \*\*([^*]+)\*\* \(([^,)]+)(?:, ([^)]*))?\): (.*)$", ln)
        if m and cur is not None:
            cur["findings"].append({"finding": m.group(1), "doc": m.group(2), "pages": m.group(3), "text": m.group(4)})
    below = []
    for ln in lines[end + 1:]:
        m = re.match(r"^- (\w+) `([^`]+)`: (.*)$", ln)
        if m:
            below.append({"kind": m.group(1), "id": m.group(2), "finding": m.group(3)})
    return items, below


def form_of(item, readers):
    if item["file"].startswith("forms/2025/"):
        return [Path(item["file"]).stem]
    if item["kind"] == "parameter":
        return sorted(readers.get(item["id"], []), key=lambda f: (rank([f]), f)) or ["(unread)"]
    return [item["file"]]


def rank(forms):
    idx = [PRIORITY.index(f) for f in forms if f in PRIORITY]
    return (0, min(idx)) if idx else (1, 0)


def main():
    items, below = parse()
    readers = param_readers()
    ids = id_files()
    a, b = [], []
    for it in items:
        it["forms"] = form_of(it, readers)
        kinds = {f["finding"] for f in it["findings"]}
        it["class"] = "b" if kinds == {NO_EDITION} else "a"
        it["missing_docs"] = sorted({f["doc"] for f in it["findings"] if f["finding"] == NO_EDITION})
        (a if it["class"] == "a" else b).append(it)
    for it in below:
        if it["kind"] == "parameter":
            it["forms"] = sorted(readers.get(it["id"], []), key=lambda f: (rank([f]), f)) or ["(unread parameter)"]
        elif it["kind"] == "ambiguity":
            it["forms"] = ["ambiguities/2025.yaml"]
        elif it["kind"] in ("enum", "table"):
            it["forms"] = [f"{it['kind']}s"]
        else:
            bare = it["id"].lstrip("$")
            it["forms"] = [ids.get(bare) or bare.split(".")[0]]
    key = lambda it: (rank(it["forms"]), it["forms"][0], it["kind"], it["id"])
    a.sort(key=key); b.sort(key=key)
    out = {"source": str(REPORT.relative_to(ROOT)), "a": a, "b": b, "below": below}
    (ROOT / "research/ty2026/worklist.json").write_text(json.dumps(out, indent=1) + "\n")

    md = ["# The 2026 worklist, split", "",
          "Generated by `research/ty2026/split_worklist.py` from `reports/2026/year_diff_from_2025.md` (the 2025",
          "definitions' citations read against the 2025 and 2026 archives after the step 1 refresh). An item is",
          "**(a)** when at least one of its findings is changed text or an amount in a document that has a 2026",
          "source (a heading or quote printed in one year only, a probable value change, or text or figures near",
          "the citation that differ); **(b)** when every",
          "finding is that a cited document has no 2026 edition archived yet. An (a) item may also carry (b)",
          "findings for its other segments. Items below the worklist (nearby text only) are counted per form;",
          "step 3 reads them for the priority forms. Priority forms first (TY2026 brief), then the rest by form.",
          "Parameters are placed under the forms whose lines read them.", "",
          f"| | items |", "|---|---|", f"| (a) changed text or amounts, 2026 source exists | {len(a)} |",
          f"| (b) waiting only for a 2026 source | {len(b)} |", f"| below the worklist (nearby differences only) | {len(below)} |", ""]
    miss = collections.Counter(d for it in b for d in it["missing_docs"])
    md += ["## (b) by missing document", "", "| document | items waiting on it |", "|---|---|"]
    md += [f"| `{d}` | {n} |" for d, n in miss.most_common()]
    md += ["", "## (a) by form", ""]
    byform = collections.OrderedDict()
    for it in a:
        byform.setdefault(it["forms"][0], []).append(it)
    for f, its in byform.items():
        tag = " (priority: %s)" % PRIORITY_NAMES[f] if f in PRIORITY else ""
        md.append(f"### {f}{tag}: {len(its)} items")
        md.append("")
        for it in its:
            strong = [x for x in it["findings"] if x["finding"] != NO_EDITION]
            kinds = collections.Counter(x["finding"] for x in strong)
            docs = sorted({x["doc"] for x in strong})
            extra = f"; also waits on {', '.join(it['missing_docs'])}" if it["missing_docs"] else ""
            md.append(f"- {it['kind']} `{it['id']}`: " + ", ".join(f"{k} ×{n}" for k, n in kinds.items())
                      + f" ({', '.join(docs)}){extra}")
        md.append("")
    md += ["## (b) by form", ""]
    byform = collections.OrderedDict()
    for it in b:
        byform.setdefault(it["forms"][0], []).append(it)
    for f, its in byform.items():
        tag = " (priority)" if f in PRIORITY else ""
        md.append(f"- {f}{tag}: {len(its)} items, waiting on " + ", ".join(sorted({d for it in its for d in it['missing_docs']})))
    md += ["", "## Below the worklist, by form", ""]
    cnt = collections.Counter()
    for it in below:
        cnt[it["forms"][0]] += 1
    md += [f"- {f}{' (priority)' if f in PRIORITY else ''}: {n}" for f, n in sorted(cnt.items(), key=lambda kv: (rank([kv[0]]), str(kv[0])))]
    (ROOT / "reports/2026/worklist_split.md").write_text("\n".join(md) + "\n")
    print(f"(a) {len(a)}  (b) {len(b)}  below {len(below)}")


if __name__ == "__main__":
    main()
